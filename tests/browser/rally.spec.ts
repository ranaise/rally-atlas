test('desktop, tablet and mobile layouts fit and can be captured', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.placement-total')).toHaveText('6,726')
  await page.evaluate(() => document.fonts.ready)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(1440)
  if (process.env.CAPTURE_SCREENSHOTS) {
    await page.screenshot({ path: 'docs/screenshots/court-explorer.png' })
    await page.locator('#explorer').screenshot({ path: 'docs/screenshots/shot-placement.png' })
    await page.getByRole('tab', { name: 'Compare players' }).click()
    await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur())
    await page.locator('#explorer').screenshot({ path: 'docs/screenshots/player-comparison.png' })
    await page.getByRole('tab', { name: 'Density' }).click()
    await page.locator('#microscope').screenshot({ path: 'docs/screenshots/rally-microscope.png' })
    for (const [tab, file] of [['Shot selection', 'shot-selection'], ['Rally lengths', 'rally-lengths'], ['Shot sequence', 'shot-sequence'], ['Rally outcomes', 'rally-outcomes']]) {
      await page.getByRole('tab', { name: tab, exact: true }).click()
      await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur())
      await page.locator('#fingerprint').screenshot({ path: `docs/screenshots/${file}.png` })
    }
    await page.locator('#findings').screenshot({ path: 'docs/screenshots/scouting-insights.png' })
  }
  for (const width of [1024, 768, 390]) {
    await page.setViewportSize({ width, height: width === 390 ? 1140 : 1020 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    await page.getByRole('tab', { name: 'Shot sequence', exact: true }).click()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
  }
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  if (process.env.CAPTURE_SCREENSHOTS) await page.screenshot({ path: 'docs/screenshots/mobile.png' })
  await page.getByRole('tab', { name: 'Court zones', exact: true }).click()
  await expect(page.locator('.zone-mark')).toHaveCount(6)
  await page.setViewportSize({ width: 320, height: 820 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})

test('relative asset paths work under a GitHub Pages-style prefix', async ({ page }) => {
  const origin = 'http://127.0.0.1:4180'
  const prefix = '/rally-atlas'
  const paths: string[] = []
  await page.route(`${origin}/**`, async route => {
    const url = new URL(route.request().url())
    paths.push(url.pathname)
    if (!url.pathname.startsWith(`${prefix}/`)) {
      await route.abort()
      return
    }
    const response = await route.fetch({ url: origin + url.pathname.slice(prefix.length) })
    await route.fulfill({ response })
  })
  await page.goto(`${prefix}/`)
  await expect(page.locator('.placement-total')).toHaveText('6,726')
  await page.evaluate(() => document.fonts.ready)
  expect(paths).toContain(`${prefix}/data/shuttleset.json`)
  expect(paths.every(path => path.startsWith(`${prefix}/`))).toBe(true)
})
